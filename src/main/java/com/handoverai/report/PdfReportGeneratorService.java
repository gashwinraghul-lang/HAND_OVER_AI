package com.handoverai.report;

import com.handoverai.entity.*;
import com.lowagie.text.*;
import com.lowagie.text.pdf.*;
import org.springframework.stereotype.Service;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.FileOutputStream;
import java.time.format.DateTimeFormatter;
import java.util.List;

@Service
public class PdfReportGeneratorService {

    public byte[] generateHandoverPdf(Project project,
                                     HandoverReport report,
                                     List<TaskItem> tasks,
                                     List<DecisionItem> decisions,
                                     List<RiskItem> risks,
                                     List<AccessItem> accessItems,
                                     List<OnboardingPlan> onboardingPlans) {
        try (ByteArrayOutputStream baos = new ByteArrayOutputStream()) {
            com.lowagie.text.Document doc = new com.lowagie.text.Document(PageSize.A4, 40, 40, 50, 50);
            PdfWriter.getInstance(doc, baos);
            doc.open();

            // Colors
            Color navyPrimary = new Color(15, 32, 67);
            Color tealAccent = new Color(0, 150, 136);
            Color textDark = new Color(33, 37, 41);

            // Fonts
            Font titleFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 22, navyPrimary);
            Font subtitleFont = FontFactory.getFont(FontFactory.HELVETICA, 11, Color.GRAY);
            Font sectionFont = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 14, navyPrimary);
            Font bodyFont = FontFactory.getFont(FontFactory.HELVETICA, 10, textDark);
            Font bodyBold = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 10, textDark);

            // Header Banner
            Paragraph brand = new Paragraph("HandOver.AI — Knowledge Continuity Platform", subtitleFont);
            brand.setAlignment(Element.ALIGN_RIGHT);
            doc.add(brand);

            Paragraph title = new Paragraph("Executive Handover Report", titleFont);
            title.setSpacingBefore(10);
            title.setSpacingAfter(5);
            doc.add(title);

            Paragraph tagline = new Paragraph("\"Preserve Knowledge. Empower People. Ensure Continuity.\"", subtitleFont);
            tagline.setSpacingAfter(20);
            doc.add(tagline);

            // Project Metadata Table
            PdfPTable metaTable = new PdfPTable(2);
            metaTable.setWidthPercentage(100);
            metaTable.setSpacingAfter(20);

            PdfPCell cell1 = new PdfPCell(new Phrase("Project: " + project.getName(), bodyBold));
            cell1.setBackgroundColor(new Color(245, 247, 250));
            cell1.setPadding(8);
            cell1.setBorderColor(new Color(220, 225, 230));

            PdfPCell cell2 = new PdfPCell(new Phrase("Readiness Score: " + project.getReadinessScore() + "%", bodyBold));
            cell2.setBackgroundColor(new Color(245, 247, 250));
            cell2.setPadding(8);
            cell2.setBorderColor(new Color(220, 225, 230));

            PdfPCell cell3 = new PdfPCell(new Phrase("Status: " + report.getStatus(), bodyFont));
            cell3.setPadding(8);
            cell3.setBorderColor(new Color(220, 225, 230));

            PdfPCell cell4 = new PdfPCell(new Phrase("Version: " + report.getVersion(), bodyFont));
            cell4.setPadding(8);
            cell4.setBorderColor(new Color(220, 225, 230));

            metaTable.addCell(cell1);
            metaTable.addCell(cell2);
            metaTable.addCell(cell3);
            metaTable.addCell(cell4);
            doc.add(metaTable);

            // Executive Summary
            doc.add(new Paragraph("1. Executive Summary", sectionFont));
            Paragraph summaryP = new Paragraph(report.getExecutiveSummary() != null ? report.getExecutiveSummary() : "Comprehensive project handover generated by HandOver.AI.", bodyFont);
            summaryP.setSpacingBefore(6);
            summaryP.setSpacingAfter(15);
            doc.add(summaryP);

            // Work Progress & Connected Tasks
            doc.add(new Paragraph("2. Connected Work & Progress Tracking", sectionFont));
            PdfPTable taskTable = new PdfPTable(4);
            taskTable.setWidthPercentage(100);
            taskTable.setSpacingBefore(8);
            taskTable.setSpacingAfter(15);

            String[] taskHeaders = {"Task / Item", "Status", "Owner", "Deadline"};
            for (String h : taskHeaders) {
                PdfPCell th = new PdfPCell(new Phrase(h, bodyBold));
                th.setBackgroundColor(new Color(235, 240, 248));
                th.setPadding(6);
                taskTable.addCell(th);
            }

            for (TaskItem t : tasks) {
                taskTable.addCell(new Phrase(t.getTitle(), bodyFont));
                taskTable.addCell(new Phrase(t.getStatus(), bodyFont));
                taskTable.addCell(new Phrase(t.getOwner() != null ? t.getOwner() : "Unassigned", bodyFont));
                taskTable.addCell(new Phrase(t.getDeadline() != null ? t.getDeadline().toString() : "None", bodyFont));
            }
            doc.add(taskTable);

            // Decisions and Risks
            doc.add(new Paragraph("3. Key Decisions & Open Risks", sectionFont));
            Paragraph decP = new Paragraph("Recent Decisions:", bodyBold);
            decP.setSpacingBefore(6);
            doc.add(decP);

            for (DecisionItem d : decisions) {
                Paragraph dp = new Paragraph("• " + d.getSummary() + " [Source: " + d.getSourceCitation() + "]", bodyFont);
                dp.setIndentationLeft(10);
                doc.add(dp);
            }

            Paragraph riskP = new Paragraph("Open Risks & Knowledge Gaps:", bodyBold);
            riskP.setSpacingBefore(8);
            doc.add(riskP);

            for (RiskItem r : risks) {
                Paragraph rp = new Paragraph("• [" + r.getSeverity() + "] " + r.getDescription() + " (Mitigation: " + r.getMitigation() + ")", bodyFont);
                rp.setIndentationLeft(10);
                doc.add(rp);
            }

            // Access Inventory (Masked)
            doc.add(new Paragraph("4. Access & Systems Inventory", sectionFont));
            PdfPTable accTable = new PdfPTable(3);
            accTable.setWidthPercentage(100);
            accTable.setSpacingBefore(8);
            accTable.setSpacingAfter(15);

            String[] accHeaders = {"System / Service", "Account ID (Masked)", "Transfer Status"};
            for (String h : accHeaders) {
                PdfPCell th = new PdfPCell(new Phrase(h, bodyBold));
                th.setBackgroundColor(new Color(235, 240, 248));
                th.setPadding(6);
                accTable.addCell(th);
            }

            for (AccessItem a : accessItems) {
                accTable.addCell(new Phrase(a.getSystemName(), bodyFont));
                accTable.addCell(new Phrase(a.getAccountMasked(), bodyFont));
                accTable.addCell(new Phrase(a.getTransferStatus(), bodyFont));
            }
            doc.add(accTable);

            // Footer note
            Paragraph footer = new Paragraph("\n\"People may leave, but project knowledge should never be lost.\"\nReport verified and cryptographically stamped by HandOver.AI.", subtitleFont);
            footer.setAlignment(Element.ALIGN_CENTER);
            doc.add(footer);

            doc.close();
            return baos.toByteArray();
        } catch (Exception e) {
            throw new RuntimeException("Failed to generate PDF report: " + e.getMessage(), e);
        }
    }
}
